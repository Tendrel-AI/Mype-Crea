"""Generate src/labeling/octagon-glyphs.ts: glyph outlines for the octagon texts (spec G-FONT-03).

Usage (one-off, needs `pip install fonttools`):
  python3 scripts/gen-octagon-glyphs.py texgyreheros-bold.otf > src/labeling/octagon-glyphs.ts
Font: TeX Gyre Heros Bold (GUST Font License), https://mirrors.ctan.org/fonts/tex-gyre/opentype/texgyreheros-bold.otf
"""
import json
import sys

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

# Every character of every text the renderer draws (octagon-geometry-spec G-TXT-01, G-LEG-04/05, G-SET-03).
TEXTS = ['ALTO EN', 'SODIO', 'AZÚCAR', 'GRASAS', 'SATURADAS', 'CONTIENE', 'TRANS',
         'EVITAR SU CONSUMO', 'EXCESIVO', 'EVITAR SU CONSUMO EXCESIVO']

font = TTFont(sys.argv[1])
cmap, glyphs, hmtx = font.getBestCmap(), font.getGlyphSet(), font['hmtx']
out = {}
for ch in sorted(set(''.join(TEXTS))):
    name = cmap[ord(ch)]
    pen = SVGPathPen(glyphs, ntos=lambda v: ('%.1f' % v).rstrip('0').rstrip('.'))
    glyphs[name].draw(TransformPen(pen, (1, 0, 0, -1, 0, 0)))  # y down, baseline at 0
    out[ch] = {'advance': hmtx[name][0], 'd': pen.getCommands()}

print('// GENERATED by scripts/gen-octagon-glyphs.py from TeX Gyre Heros Bold (GUST Font License). Do not edit.')
print('// Outlines in font units, y pointing down, baseline at y = 0. Spec: octagon-geometry-spec G-FONT-01..04.')
print('export const UNITS_PER_EM = %d;' % font['head'].unitsPerEm)
print('export const CAP_HEIGHT = %d;' % font['OS/2'].sCapHeight)
print('export const GLYPHS: Readonly<Record<string, { readonly advance: number; readonly d: string }>> = %s;'
      % json.dumps(out, ensure_ascii=False, indent=2))
